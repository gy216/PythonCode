# 提取名字和坐标
NAMES = [c[0] for c in CITIES_DATA]
COORDS = [(c[1], c[2]) for c in CITIES_DATA]

def distance(city1, city2):
    """计算球面距离（大圆距离，更真实）"""
    lon1, lat1 = city1
    lon2, lat2 = city2
    # 转换为弧度
    lon1, lat1, lon2, lat2 = map(math.radians, [lon1, lat1, lon2, lat2])
    # Haversine 公式
    dlon = lon2 - lon1
    dlat = lat2 - lat1
    a = math.sin(dlat/2)**2 + math.cos(lat1) * math.cos(lat2) * math.sin(dlon/2)**2
    c = 2 * math.asin(math.sqrt(a))
    r = 6371  # 地球半径（公里）
    return c * r

def total_distance(route):
    """计算总路程（单位：公里）"""
    dist = 0.0
    for i in range(len(route)):
        dist += distance(COORDS[route[i]], COORDS[route[(i + 1) % len(route)]])
    return dist

def quantum_tsp():
    print(f"开始在 {len(NAMES)} 个中国城市中寻找最短物流路径...")
    print("由于城市过多，量子算法正在剧烈震荡，请耐心等待...\n")
    
    route = list(range(len(NAMES)))
    random.shuffle(route)
    
    current_dist = total_distance(route)
    best_route = route[:]
    best_dist = current_dist
    
    temp = 1000.0
    start_time = time.time()
    
    for step in range(80000):  # 增加迭代次数
        new_route = route[:]
        i, j = random.sample(range(len(NAMES)), 2)
        new_route[i], new_route[j] = new_route[j], new_route[i]
        
        new_dist = total_distance(new_route)
        
        delta = new_dist - current_dist
        if delta < 0 or random.random() < math.exp(-delta / temp):
            route = new_route
            current_dist = new_dist
            if current_dist < best_dist:
                best_dist = current_dist
                best_route = route[:]
                print(f"\n第 {step} 步：发现新纪录！总距离 = {best_dist:.2f} 公里 ")
                # 打印前几个城市看看
                preview = " → ".join(NAMES[best_route[k]] for k in range(5))
                print(f"    路线预览：{preview} ...")

        temp *= 0.99995
        
        if step % 5000 == 0 and step > 0:
            elapsed = time.time() - start_time
            print(f"进度: {step}/80000 | 当前距离: {current_dist:.2f} km | 用时: {elapsed:.1f}s")

    return best_route, best_dist

